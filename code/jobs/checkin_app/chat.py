def auto_allowed(tool_name: str, tool_input: dict) -> bool:
    """Writes the live chat makes without an Allow once card (owner decision, Nov 4: "i dont want to
    approve for calendar block creation it should auto approve"): creating a calendar event that
    invites nobody, so nothing reaches anyone else. Moving or deleting events, and any event with
    guests, still ask. Only the live pool's approver calls this; test mode refuses every write."""
    if not tool_name.startswith("mcp__") or tool_name.rsplit("__", 1)[-1] != "create_event":
        return False
    guests = (tool_input or {}).get("attendees") or (tool_input or {}).get("attendeeEmails")
    return not guests


def plan_gate(key: str, tool_name: str, booking: bool) -> str:
    """Only the Book tap books, and Book only books (Nov 10, Tier 1.3: a chat "Yes, add the e-bike" was
    taken as an OK to book, and Book also moved four tasks). In a plan chat a calendar event is
    created only in a Book turn, and a Book turn changes no other event. "" when allowed."""
    if not key.startswith("plan:") or not tool_name.startswith("mcp__"):
        return ""
    op = tool_name.rsplit("__", 1)[-1]
    if op == "create_event" and not booking:
        return ("Denied: in a plan chat only the owner's Book tap creates calendar events. His messages are "
                "changes to the proposal. Update the ```blocks fence; he books it with Book.")
    if booking and op in ("update_event", "delete_event", "respond_to_event"):
        return ("Denied: Book only creates the proposed blocks. Propose any other change in your reply "
                "for the owner to decide.")
    return ""


