class Hub:
    """Both pools, the live state of each conversation, and the approval cards."""

    def __init__(self, factory=None, *, cli_path: str | None = None, projects_dir: Path | None = None,
                 limits: dict | None = None):
        DIR.mkdir(parents=True, exist_ok=True)
        self.store = SessionStore(DB)
        self.store.clear_warm_flags()
        common = dict(cwd=config.VAULT, cli_path=cli_path or agent.claude_binary(), style_path=REPLY_STYLE,
                      model=bridge_env("TG_MODEL") or None, max_warm=1, idle_close_s=IDLE_CLOSE_S,
                      projects_dir=projects_dir, limits=limits)
        factory = factory or agent.SdkClient
        # The browser (tg_bridge/browser_gate.py) only in Live, behind the same TG_BROWSER switch.
        # on_unprompted (Nov 9): a background agent's late result is saved as its own message
        # instead of becoming the next turn's answer (Talk replies ran one turn late).
        self.live = agent.AgentPool(self.store, factory, approver=self._ask, channel=CHANNEL,
                                    browser=browser_gate.enabled(bridge_env), on_unprompted=self._unprompted,
                                    **common)
        self.test = agent.AgentPool(self.store, factory, approver=self._refuse, channel=TEST_CHANNEL,
                                    allowed=READ_ONLY, mode="default", on_unprompted=self._unprompted, **common)
        self.rt: dict[str, dict] = {}            # key -> {"busy", "labels", "approval", "session", "turn"}
        self.before_queued = None   # (key, finished turn) -> note for the queued turn (Talk, Nov 11)
        self.by_session: dict[int, str] = {}
        self._waiting: dict[str, asyncio.Future] = {}
        self._tasks: set[asyncio.Task] = set()
        self.push = _push_approval               # tests replace it
        n = recover()
        if n:
            log(f"checkin_app chat: {n} conversation(s) were mid-turn at restart, noted")

    # ---- reads -------------------------------------------------------------------

    def pending(self) -> list[dict]:
        """Every approval waiting right now, in any conversation (Nov 8, the owner: "i want to fix
        that i dont see these things in the PWA"): the app shows them on every tab."""
        out = []
        for key, rt in list(self.rt.items()):
            ap = rt.get("approval")
            if not ap:
                continue
            kind, _, rest = key.partition(":")
            out.append({"key": key, "kind": kind, "thread": rest if kind == "general" else "",
                        "title": load(key).get("title") or "Chat", "id": ap["id"], "verb": ap["verb"],
                        "shown": ap["shown"], "why": ap.get("why", ""), "speak": ap.get("speak", "")})
        return out

    def state(self, key: str) -> dict:
        conv, rt = load(key), self.rt.get(key, {})
        return {"key": key, "title": conv.get("title", ""), "messages": conv["messages"],
                "busy": bool(rt.get("busy")), "status": " · ".join(rt.get("labels", [])),
                "approval": rt.get("approval"), "said": list(rt.get("said", [])),
                # Which turn is running and owns `said` (Nov 11): Talk speaks only its own turn.
                "turn": rt.get("turn") if rt.get("busy") else None,
                **({"book": conv["book"]} if conv.get("book") else {}),
                **({"plan": conv["plan"]} if conv.get("plan") else {})}

    # ---- a turn ------------------------------------------------------------------

    def send(self, key: str, title: str, text: str, *, context: str = "", test: bool = True,
             kind: str = "task", prompt_text: str | None = None, voice: bool = False,
             hidden: bool = False, images: list[str] | None = None, book: dict | None = None) -> dict:
        """text is what the sheet shows; prompt_text, when given, is what Claude gets
        (a voice note: the bridge's transcript framing, media.frame_transcript). book (a plan
        chat's Book tap, Nov 10): {"day", "blocks"}; the turn may create calendar events and its
        result is read from the calendar into conv["book"]."""
        if book and self.rt.get(key, {}).get("busy"):
            raise Busy("Claude is still answering; Book again once it is done.")
        if self.rt.get(key, {}).get("busy"):
            # Sent while Claude is still answering (owner decision, Nov 1): shown at once and collected
            # for the turn right after this one, as the Telegram bridge does.
            conv = load(key)
            rt = self.rt[key]
            if not rt.get("queue_turn"):   # everything queued meanwhile runs as one turn
                rt["queue_turn"] = conv["turn_n"] = conv.get("turn_n", 0) + 1
            conv["messages"].append({"role": "you", "text": text, "at": _now(), "test": test, "queued": True,
                                     "turn": rt["queue_turn"],
                                     **({"voice": True} if voice else {}), **({"hidden": True} if hidden else {}),
                                     **({"images": images} if images else {})})
            save(conv)
            rt.setdefault("queue", []).append({"text": prompt_text or text, "test": test})
            return {**self.state(key), "sent_turn": rt["queue_turn"]}
        conv = load(key)
        # Every turn has an id (Nov 11), on his message and on the answer: Talk's stream speaks only
        # its own turn, and a turn that outlived its stream is told apart from the next one.
        turn = conv["turn_n"] = conv.get("turn_n", 0) + 1
        conv.update(title=title or conv.get("title", ""), kind=kind, busy=True)
        conv["messages"].append({"role": "you", "text": text, "at": _now(), "test": test, "turn": turn,
                                 **({"voice": True} if voice else {}), **({"hidden": True} if hidden else {}),
                                     **({"images": images} if images else {}), **({"book": True} if book else {})})
        if book:
            conv["book"] = {"status": "booking", "n": len(book["blocks"]), "booked": 0, "changes": [],
                            "day": book["day"].isoformat(), "at": _now()}
        save(conv)
        self.rt[key] = {"busy": True, "labels": [], "approval": None, "said": [], "turn": turn,
                        **({"book": book, "book_tools": []} if book else {})}
        task = asyncio.create_task(self._turn(key, title, prompt_text or text, context, test))
        self._tasks.add(task)
        task.add_done_callback(self._tasks.discard)
        return {**self.state(key), "sent_turn": turn}

    def prompt(self, session, title: str, text: str, context: str, test: bool, kind: str, key: str = "") -> str:
        # The box runs UTC: after 16:00 Pacific its date is already tomorrow, and a log line
        # dated by it ("Nov 4 · done") hid a task closed on Nov 3 from Progress (Nov 3).
        # Carmen's day turns at 04:00 (Nov 9): at 00:30 it is still the evening's date.
        from .adapters import clock
        today = clock._label(clock.carmen_day(dt.datetime.fromisoformat(_now())))
        meta = {"channel": "checkin-app", "conversation": title, "about": kind,
                "mode": "test" if test else "live", "sent_at": _now(),
                "today": f"{today} (Pacific, the owner's day; date every Log line with it, never the system clock)"}
        lines = ["Conversation info (untrusted metadata): " + json.dumps(meta, ensure_ascii=False)]
        if session.aborted_last_run:
            lines.append("[App note: the previous run in this conversation did not finish (stopped by "
                         "the owner, killed by the watchdog, or failed). Check what was half-done before continuing.]")
        if key.startswith("task:"):
            try:   # today's committed steps are his (Nov 9): the chat proposes, never rewrites them
                from .planning import do as dmod
                tid = key.split(":", 1)[1]
                ids = dmod.committed(clock.carmen_day(dt.datetime.fromisoformat(_now())), tid)
                if ids:
                    lines.append("[App note: the owner committed to these steps for today: "
                                 + ", ".join("^" + x for x in ids)
                                 + ". Do not reword, replace or discard them; propose any change in the chat and "
                                 "wait for his yes. Tick one only when he says he did it, with (proof: ...); if it only "
                                 "looks done, leave it open and say so.]")
            except Exception:
                pass
        if key.startswith("plan:"):
            # Its own day only, and only the Book tap books (Nov 10, Tier 1.1 and 1.3).
            try:
                pday = dt.date.fromisoformat(key.split(":", 1)[1])
                cday = clock.carmen_day(dt.datetime.fromisoformat(_now()))
                # UI r3: Claude said "today" while planning Tuesday, and "3h40" against the page's "3h 40".
                when = ("today, " if pday == cday else "") + f"{pday.strftime('%A')}, {clock._label(pday)}"
                lines.append(f"[App note: the planned day is {when}. Name it by its weekday; say \"today\" only "
                             f"for {clock._label(cday)}. Write durations as the app does: \"3h 40\", \"45 min\". "
                             "End every reply that changes blocks with one line naming what changed "
                             "(\"Changed: the race 20:30–21:30, Iceland review dropped\"). In the text, name tasks by "
                             "their titles only, never their IDs; write time ranges with an en dash (14:00–14:45); "
                             "when you offer him a choice, end that sentence with a question mark.]")
                lines.append(f"[App note: this chat plans {pday.strftime('%A')} {pday.isoformat()} only. In the ```blocks "
                             f"fence write each line as YYYY-MM-DD HH:MM-HH:MM Title, dated {pday.isoformat()}; "
                             "something for another day goes in the text with its day, never in the fence. "
                             "the owner's chat messages are changes to the proposal, never an OK to book: create "
                             "calendar events only in a turn that starts with [Book], and in that turn create "
                             "exactly the listed blocks and change nothing else.]")
            except ValueError:
                pass
        if context:
            lines.append(media.untrusted(context, "check-in app " + ("plan" if kind == "plan" else "task card")))
        lines.append(text)
        return "\n\n".join(lines)

    async def _turn(self, key: str, title: str, text: str, context: str, test: bool) -> None:
        rt = self.rt[key]
        conv = load(key)
        session, _ = self.store.switch(APP_CHAT, 0, key)
        rt["session"] = session.id
        self.by_session[session.id] = key
        pool, other = (self.test, self.live) if test else (self.live, self.test)
        ok = False
        reply, role, tools = "", "claude", []
        before = None if test else note_state(key)
        t0 = time.time()
        try:
            # One Claude session, two permission sets: the other pool's warm client goes, the
            # next turn resumes the same transcript under this one's tools.
            await other.close_session(session.id, "mode switched")
            self.store.touch_interaction(session.id)

            async def on_event(event: agent.Event) -> None:
                # Claude's text blocks as they come (Nov 8, the iPhone app's streamed Talk speaks
                # them at once). Live state only: what is saved and shown elsewhere is unchanged.
                if event.kind == "text" and (event.text or "").strip():
                    rt.setdefault("said", []).append(event.text.strip())
                if event.kind == "tool" and rt.get("book") is not None:
                    rt.setdefault("book_tools", []).append((event.name, dict(event.data or {})))
                if event.kind == "tool":
                    # What the tool touched (Nov 11): the recap counts a note only when a tool named it.
                    d_ = event.data if isinstance(event.data, dict) else {}
                    for k_ in ("file_path", "notebook_path", "path", "command"):
                        if isinstance(d_.get(k_), str):
                            rt.setdefault("hints", []).append(d_[k_][:400])
                    label = tool_label(event.name, event.data)
                    if not rt["labels"] or rt["labels"][-1] != label:
                        rt["labels"] = (rt["labels"] + [label])[-3:]

            prompt = self.prompt(session, title, text, context, test, conv.get("kind", "task"), key)
            try:
                result = await pool.run_turn(session, prompt, chat_id=APP_CHAT, thread_id=session.id,
                                             on_event=on_event)
            except agent.AuthFailed as exc:
                log(f"checkin_app chat: Claude login problem ({str(exc)[:120]})")
                reply, role = AUTH_MESSAGE.replace("<code>", "").replace("</code>", ""), "note"
                return
            except agent.Stalled as exc:
                reply, role = (f"Claude stopped producing output ({exc}) and was stopped. Nothing is "
                               "running now; send it again if you still want it."), "note"
                return
            except agent.AgentError as exc:
                log(f"checkin_app chat: turn failed: {str(exc)[:300]}")
                reply, role = f"The turn did not complete: {str(exc)[:300]}. Nothing was replayed; send it again.", "note"
                return
            if result.interrupted:
                reply, role = "Stopped.", "note"
                return
            ok, tools = True, result.tools
            reply = (("(" + " ".join(result.notes) + ")\n\n") if result.notes else "") + (result.text or "(no answer)")
        except Exception as exc:   # never leave the sheet thinking forever
            log(f"checkin_app chat: crashed ({type(exc).__name__}: {exc})")
            reply, role = f"The chat crashed ({type(exc).__name__}). Send it again.", "note"
        finally:
            # As the bridge: a good turn clears the flag, a failed one sets it, a stop set it itself.
            try:
                if ok or reply != "Stopped.":
                    self.store.set_aborted(session.id, not ok)
            except Exception:
                pass
            book = rt.pop("book", None)
            result_book = None
            if book:   # Book's outcome from the calendar itself (Nov 10, Tier 1.2)
                try:
                    from .planning import read as planning_read
                    result_book = await asyncio.to_thread(planning_read.book_result, book["day"], book["blocks"],
                                                          rt.pop("book_tools", []))
                except Exception as exc:
                    log(f"checkin_app chat: book result unread ({type(exc).__name__}: {exc})")
                    result_book = {"status": "unknown", "n": len(book["blocks"]), "booked": 0, "changes": [],
                                   "day": book["day"].isoformat(), "at": _now()}
            conv = load(key)
            conv["busy"] = False
            if result_book and not test and result_book.get("got"):
                # Booking is the final word on Do's chunks (Nov 11, M1): the booked blocks' steps.
                try:
                    from .planning import actions as planning_actions
                    keys = result_book.get("keys") or {}
                    got = [{**book["blocks"][k], "key": keys.get(str(k), "")} for k in result_book["got"] if k < len(book["blocks"])]
                    planning_actions.apply_booked(book["day"], got)
                except Exception as exc:
                    log(f"checkin_app chat: booked chunks not applied ({type(exc).__name__}: {exc})")
            if result_book:
                conv["book"] = result_book
            elif "```blocks" in (reply or ""):
                conv.pop("book", None)   # a new proposal: the last Book's outcome no longer applies
            if key.startswith("plan:") and role == "claude" and "```blocks" in (reply or ""):
                # The latest proposal, stored (copy r3: Do's banner kept the previous total): Plan's
                # sheet and Do's banner read the same blocks.
                try:
                    from .planning import read as planning_read
                    pday = dt.date.fromisoformat(key.split(":", 1)[1])
                    conv["plan"] = {"blocks": planning_read.fence_blocks(reply, pday), "at": _now()}
                except Exception as exc:
                    log(f"checkin_app chat: proposal not stored ({type(exc).__name__}: {exc})")
            if reply:
                conv["messages"].append({"role": role, "text": reply, "at": _now(), "test": test,
                                         **({"turn": rt["turn"]} if rt.get("turn") else {})})
            queue = rt.pop("queue", [])
            next_turn = rt.pop("queue_turn", None)
            if queue:   # what he sent meanwhile goes now, in one turn
                for m in conv["messages"]:
                    m.pop("queued", None)
                conv["busy"] = True
            save(conv)
            hints = rt.pop("hints", [])
            note_next = ""
            if queue and self.before_queued:   # Talk's note for a turn sent while this one ran (Nov 11)
                try:
                    note_next = self.before_queued(key, rt.get("turn")) or ""
                except Exception as exc:
                    log(f"checkin_app chat: queued note failed ({type(exc).__name__}: {exc})")
            rt.update(busy=bool(queue), labels=[], approval=None, said=[], turn=next_turn if queue else rt.get("turn"))
            if queue:
                text_next = note_next + (queue[0]["text"] if len(queue) == 1 else
                                         "Sent while you were answering:\n\n" + "\n\n".join(q["text"] for q in queue))
                task = asyncio.create_task(self._turn(key, title, text_next, "", queue[-1]["test"]))
                self._tasks.add(task)
                task.add_done_callback(self._tasks.discard)
            # Claude's side of the exchange, next to his chat_message signals, so a later read of
            # the log sees what Claude answered and did (the tools it ran), not only his words.
            from .adapters.taplog import log_event
            log_event("chat", key=key, id=key.split(":", 1)[1], title=title, test=test, ok=ok, role=role,
                      chars=len(reply), reply=reply[:1500], tools=tools[:30], hints=hints[-40:])
            if not test:
                try:
                    log_chat_delta(key, title, before, t0, len(conv["messages"]))
                except Exception as exc:
                    log(f"checkin_app chat: delta not logged ({type(exc).__name__}: {exc})")

    def _unprompted(self, session_id: int, text: str) -> None:
        """A result Claude produced between turns (a background agent finished): shown as its own
        message, marked unprompted, so Talk's stream never speaks it as the answer to his next turn;
        a later poll (/api/talk/voice, empty body) says it as an update."""
        key = self.by_session.get(session_id)
        if not key:
            log(f"checkin_app chat: unprompted result for unknown session {session_id}, dropped")
            return
        conv = load(key)
        conv["messages"].append({"role": "claude", "text": text, "at": _now(), "unprompted": True})
        save(conv)
        log(f"checkin_app chat: unprompted result saved in {key} ({len(text)} chars)")

