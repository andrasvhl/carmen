def _now() -> str:
    # Pacific, like the rest of the app: the box runs UTC (checkin_app.TZ).
    from zoneinfo import ZoneInfo
    return dt.datetime.now(ZoneInfo("America/Los_Angeles")).isoformat(timespec="seconds")


def conv_path(key: str) -> Path:
    return DIR / (hashlib.sha1(key.encode()).hexdigest()[:16] + ".json")


def load(key: str) -> dict:
    try:
        return json.loads(conv_path(key).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"key": key, "title": "", "messages": [], "busy": False}


def save(conv: dict) -> None:
    DIR.mkdir(parents=True, exist_ok=True)
    conv["messages"] = conv["messages"][-HISTORY_CAP:]
    p = conv_path(conv["key"])
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(conv, ensure_ascii=False, indent=1), encoding="utf-8")
    os.replace(tmp, p)


def thread_id(raw: str) -> str:
    """A Chat tab thread's id as the page sends it (Nov 8): letters, digits and dashes, at most 40;
    anything else, or nothing, is the default thread."""
    raw = re.sub(r"[^A-Za-z0-9-]", "", str(raw or ""))[:40]
    return raw or "main"


def thread_title(text: str, images: bool = False) -> str:
    """A thread is named by its first message, cut at a word under 60 characters."""
    t = " ".join(str(text or "").split())
    if not t:
        return "Screenshot" if images else "Chat"
    return t if len(t) <= 60 else t[:60].rsplit(" ", 1)[0] + "…"


def threads(limit: int = 30) -> list[dict]:
    """The Chat tab's threads with history, newest first: id, title, messages, last message time."""
    out = []
    for f in DIR.glob("*.json"):
        try:
            c = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        key = str(c.get("key", ""))
        msgs = [m for m in c.get("messages") or [] if not m.get("hidden")]
        if key.startswith("general:") and msgs:
            out.append({"id": key.split(":", 1)[1], "title": c.get("title") or "Chat",
                        "n": len(msgs), "at": msgs[-1].get("at", "")})
    out.sort(key=lambda x: x["at"], reverse=True)
    return out[:limit]


def summaries() -> dict:
    """{key: {"n", "at"}} for every conversation with history: the cards mark Talk with it."""
    out = {}
    for f in DIR.glob("*.json"):
        try:
            c = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if c.get("messages"):
            out[c["key"]] = {"n": len(c["messages"]), "at": c["messages"][-1].get("at", "")}
    return out


def recover() -> int:
    """A turn cut by a restart: never replayed, said once (the bridge's recover rule)."""
    n = 0
    for f in DIR.glob("*.json"):
        try:
            c = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if c.get("busy"):
            said = next((m["text"] for m in reversed(c["messages"]) if m["role"] == "you"), "")
            c["busy"] = False
            c["messages"].append({"role": "note", "at": _now(),
                                  "text": "Interrupted by a restart of the app, so this message got no answer"
                                          + (f": “{said[:300]}”" if said else "") + ". Send it again if you still want it."})
            save(c)
            n += 1
    return n


